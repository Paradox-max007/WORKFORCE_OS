-- ============================================================================
-- PULSE Workforce OS — Employee documents vault (passport / visa / Emirates
-- ID / contract)
-- ----------------------------------------------------------------------------
-- Encrypted per-employee document storage for the Add/Edit Employee form and
-- the Employee Details page.
--
-- Storage model:
--   • PRIVATE bucket 'employee-documents' — files are uploaded by the ADMIN'S
--     BROWSER already encrypted with AES-256-GCM (object layout:
--     emp_<employeeId>/<kind>.<ext>.bin = iv ‖ ciphertext), so even direct
--     bucket access reveals nothing usable.
--   • the AES key lives in a one-row `document_vault_key` table OUTSIDE the
--     bucket — readable only by authenticated admins. It is generated by the
--     app on first use (client-side, random 256-bit) and never logged.
--
-- Run once in the Supabase SQL editor (Dashboard → SQL → New query).
-- Re-running is safe — every statement is idempotent.
-- ============================================================================

-- 1. the bucket (private, 20 MB per file — encrypted uploads stay under the
--    client's 15 MB plaintext limit) ------------------------------------------
insert into storage.buckets (id, name, public, file_size_limit)
values ('employee-documents', 'employee-documents', false, 20971520)
on conflict (id) do update
  set public         = false,
      file_size_limit = 20971520;

-- 2. bucket policies — authenticated admins only -------------------------------
drop policy if exists "employee documents: admins select" on storage.objects;
drop policy if exists "employee documents: admins insert" on storage.objects;
drop policy if exists "employee documents: admins update" on storage.objects;
drop policy if exists "employee documents: admins delete" on storage.objects;

create policy "employee documents: admins select"
  on storage.objects for select to authenticated
  using (
    bucket_id = 'employee-documents'
    and exists (
      select 1 from public.profiles p
      where p.id = auth.uid() and p.role in ('admin', 'super_admin')
    )
  );

create policy "employee documents: admins insert"
  on storage.objects for insert to authenticated
  with check (
    bucket_id = 'employee-documents'
    and exists (
      select 1 from public.profiles p
      where p.id = auth.uid() and p.role in ('admin', 'super_admin')
    )
  );

create policy "employee documents: admins update"
  on storage.objects for update to authenticated
  using (
    bucket_id = 'employee-documents'
    and exists (
      select 1 from public.profiles p
      where p.id = auth.uid() and p.role in ('admin', 'super_admin')
    )
  )
  with check (
    bucket_id = 'employee-documents'
    and exists (
      select 1 from public.profiles p
      where p.id = auth.uid() and p.role in ('admin', 'super_admin')
    )
  );

create policy "employee documents: admins delete"
  on storage.objects for delete to authenticated
  using (
    bucket_id = 'employee-documents'
    and exists (
      select 1 from public.profiles p
      where p.id = auth.uid() and p.role in ('admin', 'super_admin')
    )
  );

-- 3. the AES vault key — one row, admin-readable, never inside the bucket ------
create table if not exists public.document_vault_key (
  id        int primary key,
  key_b64   text not null,
  created_at timestamptz not null default now()
);

alter table public.document_vault_key enable row level security;

drop policy if exists "vault key: admins select" on public.document_vault_key;
drop policy if exists "vault key: admins insert" on public.document_vault_key;

create policy "vault key: admins select"
  on public.document_vault_key for select to authenticated
  using (
    exists (
      select 1 from public.profiles p
      where p.id = auth.uid() and p.role in ('admin', 'super_admin')
    )
  );

-- the FIRST admin to upload a document creates the key; later inserts lose
-- the race and adopt the stored key (handled by the app)
create policy "vault key: admins insert"
  on public.document_vault_key for insert to authenticated
  with check (
    exists (
      select 1 from public.profiles p
      where p.id = auth.uid() and p.role in ('admin', 'super_admin')
    )
  );
